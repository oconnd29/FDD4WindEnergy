"""Readable Markdown dump of an evaluation protocol."""

from __future__ import annotations

from fdd_eval.domain.advisor import recommend
from fdd_eval.domain.choices import CHOICES
from fdd_eval.domain.completeness import metric_validity, summarise
from fdd_eval.domain.project import Project
from fdd_eval.domain.reproducibility import TIPS, tip_state


def _label(choice_id: str) -> str:
    if not choice_id:
        return "—"
    choice = CHOICES.get(choice_id)
    return choice.label if choice else choice_id


def _labels(ids: list[str]) -> str:
    return ", ".join(_label(i) for i in ids) if ids else "—"


def export_markdown(project: Project) -> str:
    c = summarise(project)
    lines = [
        f"# {project.title}",
        "",
        "Evaluation protocol generated by **FDD Evaluation** (Chapter 7 framework).",
        "",
        f"- Created: {project.created}",
        f"- Modified: {project.modified}",
        f"- Protocol completeness: {c.required_done} / {c.required_total} required nodes",
        "",
        "## Inputs",
        "",
        f"- Operational data types: {_labels(project.inputs.data_types)}",
        f"- Evidence records: {_labels(project.inputs.records)}",
        f"- Operational-cost inputs: {_labels(project.inputs.cost_inputs)}",
        f"- Method under evaluation: {_label(project.inputs.method)}",
    ]
    if project.inputs.method_notes.strip():
        lines += ["", project.inputs.method_notes.strip()]

    s1 = project.stage1
    lines += [
        "",
        "## Stage 1 — Evaluation Objective",
        "",
        f"- Primary objective: **{_label(s1.primary_objective)}**",
        f"- Secondary objectives: {_labels(s1.secondary_objectives)}",
        f"- Reference event: {s1.early_warning.reference_event or '—'}",
        f"- Detection point: {_label(s1.early_warning.detection_point)}",
        f"- Useful lead time (planning): {s1.maintenance.useful_lead_time or '—'}",
        f"- Acceptable false fault detections: {s1.maintenance.acceptable_false_fd or '—'}",
        f"- Workload unit: {s1.maintenance.workload_unit or '—'}",
        f"- Diagnostic level: {s1.diagnostic.diagnostic_level or '—'}",
        f"- Cost terms: {_labels(s1.cost_impact.cost_terms) if s1.cost_impact.cost_terms else _labels(project.inputs.cost_inputs)}",
        f"- Sensitivity analysis planned: {'yes' if s1.cost_impact.sensitivity_planned else 'not stated'}",
    ]
    cm = s1.cost_impact.model
    if project.has_objective("obj_cost") or s1.cost_impact.cost_terms or project.inputs.cost_inputs:
        lines += [
            f"- Selling price: {cm.price_eur_per_mwh:.1f} €/MWh",
            f"- Crew visit if a healthy turbine is flagged: €{cm.inspection_eur:,.0f}",
            f"- Repair if you catch it early: €{cm.planned_repair_eur:,.0f} plus {cm.planned_downtime_h:.0f} h stop",
            f"- Repair if you wait until the blade fails: €{cm.emergency_repair_eur:,.0f} plus {cm.emergency_downtime_h:.0f} h stop",
            f"- Rated power used in the cost model: {cm.rated_power_kw:.0f} kW",
        ]
        if cm.notes.strip():
            lines += ["", cm.notes.strip()]
        if s1.cost_impact.notes.strip():
            lines += ["", s1.cost_impact.notes.strip()]

    s2 = project.stage2
    lines += [
        "",
        "## Stage 2 — Ground-Truth Development",
        "",
        f"- Fault definition: {s2.fault_definition or '—'}",
        f"- Labelled level: {s2.labelled_level or '—'}",
        f"- Evidence tier: {_label(s2.evidence_tier)}",
        f"- Evidence sources: {_labels(s2.evidence_sources)}",
        f"- Symptom method (Tier C): {_label(s2.symptom_method)}",
        f"- Label representation: {_label(s2.label_representation)}",
        f"- Evidence certainty: {_label(s2.uncertainty.evidence_certainty)}",
        f"- Timing certainty: {_label(s2.uncertainty.timing_certainty)}",
        f"- Source agreement: {_label(s2.uncertainty.source_agreement)}",
        f"- Label stability: {_label(s2.uncertainty.label_stability)}",
        f"- Healthy-case evidence: {s2.healthy_case_evidence or '—'}",
        f"- Circular-evaluation risk flagged: {'yes' if s2.circular_risk else 'no'}",
    ]

    s3 = project.stage3
    ew = s3.event_windows
    lines += [
        "",
        "## Stage 3 — Evaluation Design",
        "",
        f"- Case construction: {_label(s3.case_construction)}",
        f"- Case notes: {s3.case_notes or '—'}",
        f"- Event-window kind: {_label(ew.window_kind)}",
        f"- Window boundaries: {ew.boundaries or '—'}",
        f"- Window reference event: {ew.reference_event or s1.early_warning.reference_event or '—'}",
        f"- Timing rules: {ew.timing_rules or '—'}",
        f"- Faulty–healthy comparison: {_label(s3.comparison)}",
        f"- Training period: {s3.data_periods.training or '—'}",
        f"- Validation period: {s3.data_periods.validation or '—'}",
        f"- Test period: {s3.data_periods.test or '—'}",
        f"- Valid evaluation data: {s3.valid_data_rules or '—'}",
        f"- Tuning: {_label(s3.tuning_mode)}",
        f"- Tuning inventory: {_label(s3.tuning_inventory)}",
        f"- Fault-detection condition: {_label(s3.fd_condition)}",
        f"- Fault-detection notes: {s3.fd_condition_notes or '—'}",
    ]

    s4 = project.stage4
    lines += [
        "",
        "## Stage 4 — Metric Selection",
        "",
        f"- Output class: {_label(s4.output_class)}",
        f"- Output type: {_label(s4.output_score)}",
        f"- Stability / nuisance measures: {_label(s4.include_stability)}",
        "",
        "### Recommended metric set",
        "",
    ]
    recs = recommend(project)
    if not recs:
        lines.append("No recommendations yet — choose a primary objective.")
    for rec in recs:
        accepted = rec.metric.id in s4.accepted_metrics
        rejected = rec.metric.id in s4.rejected_metrics
        flag = "accepted" if accepted else "rejected" if rejected else "suggested"
        valid = "valid on current protocol" if rec.valid else "not yet valid"
        lines += [
            f"- **{rec.metric.name}** ({rec.metric.unit}; {flag}; {valid})",
            f"  - Why: {rec.reason}",
            f"  - Limitation: {rec.metric.limitation}",
        ]
        if rec.missing:
            lines.append("  - Missing for validity: " + "; ".join(rec.missing))
        if rec.metric.citations:
            lines.append("  - " + "; ".join(rec.metric.citations))
    if s4.override_notes.strip():
        lines += ["", "### Override notes", "", s4.override_notes.strip()]

    if c.missing_required:
        lines += ["", "## Missing required protocol items", ""]
        for _nid, msg in c.missing_required:
            lines.append(f"- {msg}")

    lines += ["", "## Reproducibility notes (recommended)", ""]
    for tip in TIPS:
        state = tip_state(project, tip.id)
        lines.append(f"- {tip.title}: **{state}** — {tip.ideal}")
    if project.reproducibility.notes.strip():
        lines += ["", project.reproducibility.notes.strip()]
    if project.notes.strip():
        lines += ["", "## Project notes", "", project.notes.strip()]
    lines.append("")
    return "\n".join(lines)
